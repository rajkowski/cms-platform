    @Test
    void appRepository_addAndFindByPublicKey() {
        App app = new App();
        app.setName("SDK App");
        app.setSummary("SDK summary");
        app.setPublicKey("public-key-2");
        app.setPrivateKey("private-key-2");
        app.setCreatedBy(1L);

        App saved = AppRepository.save(app);
        assertNotNull(saved);
        assertTrue(saved.getId() > 0);

        App found = AppRepository.findByPublicKey("public-key-2");
        assertNotNull(found);
        assertEquals("SDK App", found.getName());
        assertEquals("private-key-2", found.getPrivateKey());
    }

    @Test
    void blockedIPRepository_addAndFindByIpAddress() {
        BlockedIP blockedIP = new BlockedIP();
        blockedIP.setIpAddress("10.0.0.1");
        blockedIP.setReason("Known abuse");

        BlockedIP saved = BlockedIPRepository.add(blockedIP);
        assertNotNull(saved);
        assertTrue(saved.getId() > 0);

        BlockedIP found = BlockedIPRepository.findByIpAddress("10.0.0.1");
        assertNotNull(found);
        assertEquals("Known abuse", found.getReason());
        assertEquals(2, BlockedIPRepository.findAll(new DataConstraints()).size());
    }


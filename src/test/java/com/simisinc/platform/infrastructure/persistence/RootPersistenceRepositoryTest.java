    @Test
    void sessionRepository_addAndCountSessions() throws SQLException {
        Session session = new Session();
        session.setSessionId("sess-123");
        session.setSource("web");
        session.setIpAddress("127.0.0.1");
        session.setUserAgent("Mozilla/5.0");
        session.setReferer("https://example.com");
        session.setCountry("United States");
        session.setCity("Austin");
        session.setState("TX");
        session.setLatitude(30.2672);
        session.setLongitude(-97.7431);
        session.setIsBot(false);

        Session saved = SessionRepository.add(session);
        assertNotNull(saved);
        assertTrue(saved.getId() > 0);

        List<Session> sessions = SessionRepository.findAll();
        assertNotNull(sessions);
        assertFalse(sessions.isEmpty());
        assertEquals("sess-123", sessions.get(0).getSessionId());

        Timestamp start = new Timestamp(System.currentTimeMillis() - 60000);
        Timestamp end = new Timestamp(System.currentTimeMillis() + 60000);
        assertEquals(1, SessionRepository.countDistinctSessions(start, end));
    }

